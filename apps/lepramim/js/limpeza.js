/* ============================================================
   LêPraMim — limpeza.js
   "Inteligência de limpeza": transforma o texto bruto de um
   documento em algo agradável de ouvir, removendo o que um
   narrador profissional não leria.

   Remove (cada item pode ser desligado nas Configurações):
   - cabeçalhos e rodapés repetidos
   - numeração de páginas
   - URLs, copyrights, créditos e notas repetidos
   - linhas de ISBN
   - índices e sumários
   - propagandas e assinaturas

   Entrada: conteudo = { paginado, paginas: [[bloco, …], …] }
     paginado = true  -> cada bloco é uma LINHA de uma página real (PDF/OCR)
     paginado = false -> cada bloco é um PARÁGRAFO de uma seção (EPUB, DOCX…)
     bloco = { t: texto, q: começa parágrafo, a: altura da letra, y: posição 0..1, h: nível de título }
   Saída: { secoes: [[{t,h}, …], …], relatorio }
   ============================================================ */
(function () {
  'use strict';
  const { normalizar } = LPM.util;

  /* ---------- Padrões ---------- */
  const ROMANO = /^(?=[ivxlcdm])m{0,3}(cm|cd|d?c{0,3})(xc|xl|l?x{0,3})(ix|iv|v?i{0,3})$/i;
  // "Página 12", "Pág. 3 de 40", "Page 7/90" — em qualquer lugar da página
  const PAGINA_EXPLICITA = /^(p[aá]g(ina)?\.?|page)\s*\d{1,4}(\s*(de|of|\/)\s*\d{1,4})?\.?$/i;
  // "12", "- 12 -", "12/300", "| 7" — só vale no topo ou no pé da página
  const NUMERO_SOLTO = /^[-–—|•·\[(]?\s*(\d{1,4}|[ivxlcdm]{1,7})\s*((de|of|\/)\s*\d{1,4})?\s*[-–—|•·\])]?$/i;
  const SO_DIGITOS = /^\d{1,4}$/;
  const ISBN = /\bISBN(?:[-‐ ]?1[03])?\b[:\s]*\d[\d\-‐– xX]{8,}/i;
  const URL = /(https?:\/\/|www\.)\S+|\b[\w-]+\.(com|org|net|edu|gov)(\.br)?\b/i;
  const COPYRIGHT = /©|\(c\)\s*\d{4}|\bcopyright\b|todos os direitos reservados|all rights reserved|direitos autorais reservados/i;
  const TITULO_SUMARIO = /^(sum[aá]rio|[ií]ndice(\s+(geral|anal[ií]tico|remissivo))?|conte[uú]do|contents|table of contents|index)\s*:?$/i;
  // linha de sumário com pontilhado: "Capítulo 1 ........ 15"
  const SUMARIO_FORTE = /(\.{3,}|(\.\s){3,}|…{2,}|_{3,}|·{3,})\s*(\d{1,4}|[ivxlcdm]{1,7})\s*$/i;
  // linha de sumário simples: "A chegada 15"
  const SUMARIO_FRACO = /^\D.{1,90}\s\d{1,4}$/;
  const PROPAGANDA = /(compre (j[aá]|agora)|clique aqui|acesse (j[aá]|agora|nosso site|o nosso site)|visite (o )?nosso site|siga-nos|siga a gente|curta nossa p[aá]gina|baixe (gr[aá]tis|agora|o app|o aplicativo)|assine (j[aá]|agora)|oferta (especial|imperd[ií]vel)|frete gr[aá]tis|cupom de desconto|inscreva-se (j[aá]|agora|no canal)|subscribe now|buy now|click here|follow us on|visit our website|download (now|for free)|special offer)/i;
  const PROPAGANDA_LINHA = /^(publicidade|an[uú]ncio|advertisement|sponsored|patrocinado)$/i;
  const ASSINATURA = /^(enviado do meu|sent from my|atenciosamente,?$|att\.?,?$|cordialmente,?$|best regards,?$|kind regards,?$|sincerely,?$|digitalizado por|digitaliza[cç][aã]o:|scanned by|created with|criado com|generated by|gerado por|convertido por|converted by|distribu[ií]do gratuitamente|este e-?book foi (baixado|disponibilizado))/i;
  const DIALOGO = /^[—–\-"“«]\s?/;

  /** Chave exata: só ignora acentos, maiúsculas e espaços ("Exercício 1" ≠ "Exercício 2"). */
  function chaveExata(t) {
    return normalizar(t).replace(/\s+/g, ' ').trim();
  }

  /** Chave usada em cabeçalhos/rodapés: também ignora os números ("Livro — 12" = "Livro — 13"). */
  function chave(t) {
    const n = normalizar(t).replace(/\s+/g, ' ').trim();
    // títulos de capítulo mantêm o número: "Capítulo 3" ≠ "Capítulo 4"
    return LPM.capitulos.ehTitulo(t) ? n : n.replace(/\d+/g, '#');
  }

  function novoRelatorio() {
    return { cabecalhos: 0, rodapes: 0, numeros: 0, urls: 0, copyrights: 0, isbn: 0, sumarios: 0, propagandas: 0, repetidos: 0, total: 0 };
  }

  /* ============================================================
     Regras que valem para qualquer formato
     unidades: [[bloco, …], …]  (páginas ou seções) — marca bloco.rm = true
     ============================================================ */
  function regrasGerais(unidades, op, rel, paginado) {
    const n = unidades.length;
    const urls = new Map(), direitos = new Map(), gerais = new Map();
    const somar = (mapa, k, ui) => { let s = mapa.get(k); if (!s) mapa.set(k, s = { vezes: 0, unidades: new Set() }); s.vezes++; s.unidades.add(ui); };

    // 1ª passada: conta repetições no documento inteiro
    unidades.forEach((un, ui) => un.forEach(b => {
      if (b.rm) return;
      const t = b.t, tam = t.length;
      if (tam < 110 && URL.test(t)) somar(urls, chaveExata(t), ui);
      if (tam < 200 && COPYRIGHT.test(t)) somar(direitos, chave(t), ui);
      // Em páginas reais só contam linhas que iniciam um parágrafo: a última
      // linha de um parágrafo ("disse ela.") pode se repetir por acaso.
      if (tam >= 12 && tam <= 120 && (!paginado || b.q) && !DIALOGO.test(t) && !LPM.capitulos.ehTitulo(t)) somar(gerais, chaveExata(t), ui);
    }));

    const minimoGeral = paginado ? Math.max(4, Math.ceil(n * 0.05)) : 5;

    // 2ª passada: remove
    unidades.forEach(un => un.forEach(b => {
      if (b.rm) return;
      const t = b.t, tam = t.length;
      let k = null;
      const ch = () => (k === null ? (k = chave(t)) : k);

      if (op.numeros && PAGINA_EXPLICITA.test(t)) { b.rm = true; rel.numeros++; return; }
      if (op.isbn && tam < 100 && ISBN.test(t)) { b.rm = true; rel.isbn++; return; }
      if (op.urls && tam < 110 && URL.test(t) && urls.get(chaveExata(t)).vezes >= 3) { b.rm = true; rel.urls++; return; }
      if (op.copyrights && tam < 200 && COPYRIGHT.test(t) && direitos.get(ch()) && direitos.get(ch()).vezes >= 2) { b.rm = true; rel.copyrights++; return; }
      if (op.propagandas && tam < 160 && (PROPAGANDA.test(t) || PROPAGANDA_LINHA.test(t) || ASSINATURA.test(t))) { b.rm = true; rel.propagandas++; return; }
      if (op.repetidos && tam >= 12 && tam <= 120 && (!paginado || b.q)) {
        const g = gerais.get(chaveExata(t));
        if (g && (paginado ? g.unidades.size : g.vezes) >= minimoGeral) { b.rm = true; rel.repetidos++; }
      }
    }));
  }

  /* ============================================================
     Documentos com páginas reais (PDF, OCR, TXT com quebra de página)
     ============================================================ */
  function limparPaginado(paginas, op, rel) {
    const n = paginas.length;
    const P = paginas.map(pg => pg
      .filter(l => l && l.t && l.t.trim())
      .map(l => ({ t: l.t.replace(/\s+/g, ' ').trim(), q: !!l.q, a: l.a, y: l.y, rm: false })));

    // Marca a zona de cada linha: T = topo, B = base (pé) da página
    P.forEach(pg => pg.forEach((l, i) => {
      const topo = i < 3 && (l.y === undefined || l.y < 0.2);
      const base = i >= pg.length - 3 && (l.y === undefined || l.y > 0.8);
      l.z = topo ? 'T' : (base ? 'B' : '');
    }));

    /* --- Cabeçalhos e rodapés repetidos ---
       Uma linha que aparece no topo (ou no pé) de 3 ou mais páginas
       é classificada como cabeçalho (ou rodapé) e removida. */
    if (op.cabecalhos && n >= 3) {
      const cont = new Map();
      P.forEach((pg, pi) => pg.forEach(l => {
        if (!l.z || l.t.length > 120 || DIALOGO.test(l.t)) return;
        if (SO_DIGITOS.test(l.t)) return; // números puros são tratados como numeração
        const k = l.z + '|' + chave(l.t);
        let s = cont.get(k);
        if (!s) cont.set(k, s = new Set());
        s.add(pi);
      }));
      const mantidos = new Set(); // 1ª ocorrência de um título de capítulo é preservada
      P.forEach(pg => pg.forEach(l => {
        if (!l.z || l.rm) return;
        const k = l.z + '|' + chave(l.t);
        const s = cont.get(k);
        if (!s || s.size < 3) return;
        if (LPM.capitulos.ehTitulo(l.t) && !mantidos.has(k)) { mantidos.add(k); return; }
        l.rm = true;
        if (l.z === 'T') rel.cabecalhos++; else rel.rodapes++;
      }));
    }

    /* --- Numeração de páginas no topo ou no pé --- */
    if (op.numeros) {
      P.forEach(pg => pg.forEach(l => {
        if (l.rm || !l.z) return;
        const m = NUMERO_SOLTO.exec(l.t);
        if (!m) return;
        // se for romano, precisa ser um numeral válido (evita apagar palavras)
        if (!/^\d+$/.test(m[1]) && !ROMANO.test(m[1])) return;
        l.rm = true; rel.numeros++;
      }));
    }

    /* --- Sumários e índices: páginas formadas por "título ..... 12" --- */
    if (op.sumarios) {
      let anteriorEraSumario = false;
      P.forEach(pg => {
        const vivas = pg.filter(l => !l.rm);
        const total = vivas.length;
        let fortes = 0, fracos = 0;
        vivas.forEach(l => { if (SUMARIO_FORTE.test(l.t)) fortes++; else if (SUMARIO_FRACO.test(l.t)) fracos++; });
        const temTitulo = vivas.slice(0, 4).some(l => TITULO_SUMARIO.test(l.t));
        const itens = fortes + fracos;
        const ehSumario = total >= 3 && (
          (fortes >= 4 && fortes >= total * 0.4) ||
          (temTitulo && itens >= 3 && itens >= total * 0.4) ||
          (anteriorEraSumario && total >= 4 && itens >= total * 0.6));
        if (ehSumario) { vivas.forEach(l => { l.rm = true; }); rel.sumarios++; }
        anteriorEraSumario = ehSumario;
      });
    }

    regrasGerais(P, op, rel, true);

    /* --- Altura "normal" da letra no documento (para reconhecer títulos grandes) --- */
    const hist = new Map();
    P.forEach(pg => pg.forEach(l => { if (!l.rm && l.a) hist.set(l.a, (hist.get(l.a) || 0) + l.t.length); }));
    let alturaCorpo = 0, maior = 0;
    hist.forEach((v, k) => { if (v > maior) { maior = v; alturaCorpo = k; } });

    return P.map(pg => montarParagrafos(pg, alturaCorpo));
  }

  /** Junta as linhas de uma página em parágrafos. */
  function montarParagrafos(linhas, alturaCorpo) {
    const pars = [];
    const vivas = linhas.filter(l => !l.rm);
    if (!vivas.length) return pars;
    const maiorLinha = vivas.reduce((m, l) => Math.max(m, l.t.length), 0);
    // Sem pistas de parágrafo (OCR, TXT): usa a pontuação para adivinhar
    const semPistas = linhas.length > 6 && linhas.slice(1).every(l => !l.q);

    let atual = null, pendente = false;
    for (const l of linhas) {
      if (l.rm) { if (l.q) pendente = true; continue; }
      const titulo = LPM.capitulos.ehTitulo(l.t);
      const grande = !!(l.a && alturaCorpo && l.a > alturaCorpo * 1.22 && l.t.length < 90);
      let novo = !atual || l.q || pendente || titulo || atual.titulo || grande !== atual.grande;
      if (!novo && semPistas) {
        novo = /[.!?…:"”»]$/.test(atual.ultima) && atual.ultima.length < maiorLinha * 0.75;
      }
      pendente = false;
      if (novo) {
        atual = { t: l.t, titulo, grande, ultima: l.t };
        pars.push(atual);
      } else {
        // palavra dividida por hífen no fim da linha: "exem-" + "plo" -> "exemplo"
        if (/[a-zà-ÿ]-$/i.test(atual.t) && /^[a-zà-ÿ]/.test(l.t)) atual.t = atual.t.slice(0, -1) + l.t;
        else atual.t += ' ' + l.t;
        atual.ultima = l.t;
      }
    }
    return pars.map(p => ({ t: p.t, h: p.titulo ? 1 : (p.grande ? 2 : 0) }));
  }

  /* ============================================================
     Documentos sem páginas (EPUB, DOCX, TXT, HTML, RTF)
     ============================================================ */
  function limparCorrido(secoes, op, rel) {
    const S = secoes.map(sec => sec
      .filter(b => b && b.t && b.t.trim())
      .map(b => ({ t: b.t.replace(/\s+/g, ' ').trim(), h: b.h || 0, rm: false })));

    /* --- Números isolados em sequência crescente = numeração de páginas --- */
    if (op.numeros) {
      const cand = [];
      S.forEach(sec => sec.forEach(b => { if (SO_DIGITOS.test(b.t)) cand.push(b); }));
      if (cand.length >= 3) {
        let crescentes = 0;
        for (let i = 1; i < cand.length; i++) {
          const d = parseInt(cand[i].t, 10) - parseInt(cand[i - 1].t, 10);
          if (d > 0 && d <= 5) crescentes++;
        }
        if (crescentes >= (cand.length - 1) * 0.7) cand.forEach(b => { b.rm = true; rel.numeros++; });
      }
    }

    /* --- Sumário: título "Sumário/Índice" seguido de uma lista de itens curtos --- */
    if (op.sumarios) {
      S.forEach(sec => {
        for (let i = 0; i < sec.length; i++) {
          if (sec[i].rm || !TITULO_SUMARIO.test(sec[i].t)) continue;
          const vistos = new Set();
          let j = i + 1, fimSeguro = false;
          for (; j < sec.length && j - i < 400; j++) {
            const t = sec[j].t, k = normalizar(t);
            // termina ao achar um parágrafo de verdade ou um título repetido
            // (o capítulo real, que já tinha aparecido na lista do sumário)
            if (t.length >= 160 || vistos.has(k)) { fimSeguro = true; break; }
            vistos.add(k);
            // guarda também sem o pontilhado e o número: "Capítulo 1 ..... 3" -> "Capítulo 1"
            vistos.add(k.replace(/[\s.…·_]*(\d{1,4}|[ivxlcdm]{1,7})?\s*$/i, ''));
          }
          // a seção inteira é o sumário (comum em EPUB, onde o sumário é um arquivo próprio)
          if (j >= sec.length && j - i >= 3 && S.length > 1) fimSeguro = true;
          if (fimSeguro && j - i >= 3) {
            for (let x = i; x < j; x++) sec[x].rm = true;
            rel.sumarios++;
            i = j - 1;
          }
        }
      });
    }

    regrasGerais(S, op, rel, false);
    return S.map(sec => sec.filter(b => !b.rm).map(b => ({ t: b.t, h: b.h })));
  }

  /* ============================================================
     Ponto de entrada
     ============================================================ */
  function processar(conteudo, opcoes) {
    const rel = novoRelatorio();
    const op = Object.assign({}, opcoes);
    if (!op.ativa) {
      // Limpeza desligada: nenhuma regra é aplicada
      Object.keys(op).forEach(k => { op[k] = false; });
    }
    const paginas = conteudo.paginas || [];
    const secoes = conteudo.paginado ? limparPaginado(paginas, op, rel) : limparCorrido(paginas, op, rel);
    rel.total = rel.cabecalhos + rel.rodapes + rel.numeros + rel.urls + rel.copyrights + rel.isbn + rel.propagandas + rel.repetidos;
    return { secoes, relatorio: rel };
  }

  LPM.limpeza = { processar };
})();
